from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

DARK = RGBColor(32, 33, 36)
GRAY = RGBColor(95, 99, 104)
LIGHT = RGBColor(245, 248, 255)


def set_bg(slide, color=RGBColor(255, 255, 255)):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def add_title(slide, title, subtitle=None):
    tx = slide.shapes.add_textbox(Inches(0.55), Inches(0.3), Inches(12.1), Inches(1.0))
    tf = tx.text_frame
    tf.clear()
    p = tf.paragraphs[0]
    p.text = title
    p.font.size = Pt(30)
    p.font.bold = True
    p.font.color.rgb = DARK
    if subtitle:
        p2 = tf.add_paragraph()
        p2.text = subtitle
        p2.font.size = Pt(14)
        p2.font.color.rgb = GRAY


def add_bullets(slide, items, left=0.8, top=1.65, width=11.7, height=5.1):
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = box.text_frame
    tf.clear()
    tf.word_wrap = True
    first = True
    for text, level in items:
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.text = text
        p.level = level
        p.font.size = Pt(18 if level == 0 else 15)
        p.font.bold = (level == 0)
        p.font.color.rgb = DARK if level == 0 else GRAY
        p.space_after = Pt(5 if level == 0 else 2)


def add_footer(slide, page, label):
    line = slide.shapes.add_shape(1, Inches(0.55), Inches(6.85), Inches(12.1), Inches(0.01))
    line.fill.solid(); line.fill.fore_color.rgb = RGBColor(220,225,235); line.line.fill.background()
    f = slide.shapes.add_textbox(Inches(0.55), Inches(6.9), Inches(10.8), Inches(0.3)).text_frame
    f.text = f"湖北厚爱健康管理有限公司｜{label}"
    f.paragraphs[0].font.size = Pt(10)
    f.paragraphs[0].font.color.rgb = GRAY
    pn = slide.shapes.add_textbox(Inches(12.1), Inches(6.86), Inches(0.5), Inches(0.3)).text_frame
    pn.text = str(page)
    pn.paragraphs[0].alignment = PP_ALIGN.RIGHT
    pn.paragraphs[0].font.size = Pt(10)
    pn.paragraphs[0].font.color.rgb = GRAY


def build(slides, out_path, label):
    prs = Presentation()
    for i, (title, subtitle, items) in enumerate(slides, 1):
        s = prs.slides.add_slide(prs.slide_layouts[6])
        set_bg(s, LIGHT if i in [1, len(slides)] else RGBColor(255,255,255))
        add_title(s, title, subtitle)
        add_bullets(s, items)
        add_footer(s, i, label)
    prs.save(out_path)

